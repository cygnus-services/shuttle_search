"""Shuttle drive-time estimation and example descent-route generation.

Both problems are least-cost paths on the shared analysis grid, solved
with scipy.sparse.csgraph Dijkstra via ``gridgraph.GridGraph``
(scikit-image's MCP was dropped after intermittent native crashes on
Python 3.14/arm64; the edge metric is identical).

Drive time
----------
Cost per meter is 1.0 on mapped road cells and ``drive_offroad_penalty``
elsewhere, so the path sticks to roads but can bridge small gaps in the
rasterized network (washouts, unmapped connectors, the walk from a
trailhead to the road). The graph is restricted to cells near roads —
anything further can't be part of a sane drive, and the restriction keeps
the graph ~10x smaller than the grid. Accumulated cost approximates *road
meters actually driven*; divide by ``avg_shuttle_speed_mph`` for time.

  ASSUMPTION: a single average speed (default 25 mph) for the whole
  network. Montana forest roads vary 10-45 mph; the 45-minute gate should
  be treated as +/- 30% until validated against real drives.

One Dijkstra sweep per unique start point covers every end point, so cost
scales with unique starts, not with pair count.

Descent routes
--------------
These are *sanity-check corridors*, not final trail alignments. The cost
surface rewards cells whose slope is close to the pair's average grade
(steady descent), and makes hazard cells effectively impassable and
unrideable-steep cells strongly discouraged. Each pair's search is
confined to a corridor around its straight line (and the graph is built
only on that corridor's bounding box, keeping per-pair work small). An
isotropic cost cannot encode travel direction, so "no intermediate
climbing" is enforced softly: after extraction we measure the elevation
profile and report total climb, which feeds scoring.

A second route (when ``routes_per_pair`` = 2) is generated by penalizing a
corridor around the first route and re-solving, guaranteeing meaningful
divergence or graceful fallback to a single route.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass

import numpy as np

from . import units
from .candidates import CandidatePair, CandidatePoint
from .config import Config
from .data_loading import Datasets
from .gridgraph import IMPASSABLE, GridGraph
from .terrain import TerrainAnalysis, buffer_mask

log = logging.getLogger(__name__)


@dataclass
class Route:
    rows: np.ndarray          # path cell rows, start -> end
    cols: np.ndarray          # path cell cols
    length_m: float           # horizontal path length (octile)
    total_climb_m: float      # sum of positive elevation gains along path
    grade_std_pct: float      # std-dev of per-segment grade (consistency)
    crosses_hazard: bool      # True if forced through an absolute hazard cell
    road_crossings: int = 0   # # of gravel+ (class>=3) road segments crossed
    crosses_cliff: bool = False  # True if forced over a cliff (no ride-around)
    pickup_overshoot_m: float = 0.0  # how far past the best pickup it ran
    road_along_m: float = 0.0        # longest mid-route stretch ON a road

    @property
    def total_climb_ft(self) -> float:
        return units.meters_to_feet(self.total_climb_m)


# ---------------------------------------------------------------------------
# Drive time
# ---------------------------------------------------------------------------

def _drive_cost_surface(data: Datasets, terrain: TerrainAnalysis,
                        cfg: Config) -> np.ndarray:
    p = cfg.params
    cost = np.full(data.grid.shape, p.drive_offroad_penalty, dtype=np.float64)
    # Per-meter cost by road TYPE class: multiplier = avg speed / class
    # speed (highway 0.5x ... jeep road 5x at the defaults).
    for cls, mult in p.road_class_costs().items():
        cost[data.road_class == cls] = mult
    # Roads over the windowed grade limit get no speed benefit — they cost
    # the same as driving cross-country.
    cost[terrain.steep_roads] = p.drive_offroad_penalty
    cost[np.isnan(data.dem_m)] = IMPASSABLE
    # A vehicle also can't ford mapped water off-bridge; roads override water
    # because bridges are part of the road raster.
    cost[data.hydro & ~data.roads] = IMPASSABLE
    return cost


def estimate_drive_times(
    pairs: list[CandidatePair],
    data: Datasets,
    terrain: TerrainAnalysis,
    cfg: Config,
) -> list[CandidatePair]:
    """Fill ``drive_time_s`` on each pair and drop pairs over the limit."""
    if not pairs:
        return []
    cost = _drive_cost_surface(data, terrain, cfg)
    cell = data.grid.cell_size_m
    speed = cfg.params.avg_shuttle_speed_mps

    # Restrict the graph to cells near roads: candidate points are within
    # the road-access limit by construction, and optimal drives never stray
    # further off-road than a gap-bridge. Generous margin, tiny graph.
    near_roads = terrain.road_distance_m <= (
        cfg.params.road_access_m + 10 * cfg.params.offroad_gap_tolerance_m
    )
    graph = GridGraph(cost, cell, mask=near_roads)
    log.info("Drive graph: %d nodes (%.1f%% of grid)",
             graph.n, 100.0 * graph.n / cost.size)

    by_start: dict[tuple[int, int], list[CandidatePair]] = {}
    for p in pairs:
        by_start.setdefault((p.start.row, p.start.col), []).append(p)

    kept: list[CandidatePair] = []
    n_degenerate = 0
    for (r0, c0), group in by_start.items():
        cum = graph.costs_from(r0, c0)
        if cum is None:
            continue
        for p in group:
            end_node = graph.node_of(p.end.row, p.end.col)
            if end_node < 0:
                continue
            acc = float(cum[end_node])
            if not np.isfinite(acc):
                continue  # no drivable connection at all
            if acc < cfg.hard.min_shuttle_drive_m:
                n_degenerate += 1  # same road spot serves both points
                continue
            p.drive_time_s = acc / speed  # cost 1.0/m on road => meters
            if p.drive_time_s <= cfg.hard.max_drive_time_s:
                kept.append(p)
    log.info(
        "Drive-time gate (<= %.0f min @ %.0f mph, >= %.1f mi drive): "
        "%d/%d pairs pass (%d degenerate same-road-spot)",
        cfg.hard.max_drive_time_min, cfg.params.avg_shuttle_speed_mph,
        cfg.hard.min_shuttle_drive_mi, len(kept), len(pairs), n_degenerate,
    )
    return kept


def build_drive_routes(
    pairs: list[CandidatePair],
    data: Datasets,
    terrain: TerrainAnalysis,
    cfg: Config,
) -> None:
    """Trace the actual road path of each shuttle drive (end -> start).

    Called on the final ranked pairs only, so a handful of Dijkstra runs.
    Populates ``pair.drive_path`` for the output layer, letting the drive
    time estimate be eyeballed against the real road it follows."""
    if not pairs:
        return
    cost = _drive_cost_surface(data, terrain, cfg)
    near_roads = terrain.road_distance_m <= (
        cfg.params.road_access_m + 10 * cfg.params.offroad_gap_tolerance_m)
    graph = GridGraph(cost, data.grid.cell_size_m, mask=near_roads)
    traced = 0
    for p in pairs:
        sp = graph.shortest_path((p.end.row, p.end.col),
                                 (p.start.row, p.start.col))
        if sp is not None:
            p.drive_path = (sp[0], sp[1])
            traced += 1
    log.info("Traced %d/%d shuttle drive routes", traced, len(pairs))


# ---------------------------------------------------------------------------
# Descent routes
# ---------------------------------------------------------------------------

def _corridor_mask(
    shape: tuple[int, int],
    start: CandidatePoint,
    end: CandidatePoint,
    run_m: float,
    cell: float,
    cfg: Config,
) -> np.ndarray:
    """True where routing is allowed: within a corridor around the pair's
    straight line, half-width = max(factor * run, min) (meters). Keeps
    example descents from wandering through unrelated terrain miles away."""
    half_w = max(cfg.params.route_corridor_factor * run_m,
                 cfg.params.route_corridor_min_m) / cell  # in cells
    rows, cols = np.mgrid[0:shape[0], 0:shape[1]].astype(np.float32)
    p0 = np.array([start.row, start.col], dtype=np.float64)
    seg = np.array([end.row - start.row, end.col - start.col],
                   dtype=np.float64)
    seg_len2 = float(seg @ seg)
    dr = rows - p0[0]
    dc = cols - p0[1]
    if seg_len2 <= 0:
        return np.hypot(dr, dc) <= half_w
    t = np.clip((dr * seg[0] + dc * seg[1]) / seg_len2, 0.0, 1.0)
    return np.hypot(dr - t * seg[0], dc - t * seg[1]) <= half_w


def _route_stats(
    rows: np.ndarray,
    cols: np.ndarray,
    data: Datasets,
    terrain: TerrainAnalysis,
) -> Route:
    cell = data.grid.cell_size_m
    dr = np.diff(rows.astype(np.float64))
    dc = np.diff(cols.astype(np.float64))
    seg_len = np.hypot(dr, dc) * cell
    elev = data.dem_m[rows, cols].astype(np.float64)
    delev = np.diff(elev)  # negative = descending
    climbs = np.clip(delev, 0, None)
    with np.errstate(divide="ignore", invalid="ignore"):
        seg_grade = np.where(seg_len > 0, -100.0 * delev / seg_len, 0.0)
    # Road interaction, measured on contiguous runs of gravel-or-better
    # (class >= 3) cells. The FIRST and LAST runs are the departure from and
    # arrival at a road — always allowed. Only middle runs count, as either
    # a crossing (short) or riding the road itself (long).
    major = data.road_class[rows, cols] >= 3
    edges = np.flatnonzero(
        np.diff(np.concatenate(([0], major.astype(np.int8), [0]))))
    run_starts, run_ends = edges[0::2], edges[1::2]
    crossings, along_m = 0, 0.0
    seg_cum = np.concatenate(([0.0], np.cumsum(seg_len)))
    for a, b in zip(run_starts, run_ends):
        if a == 0 or b >= len(major):
            continue  # terminal run: departing/arriving at a road
        crossings += 1
        along_m = max(along_m, float(seg_cum[min(b, len(seg_cum) - 1)]
                                     - seg_cum[a]))
    # Pickup overshoot: distance-to-road at the finish vs the closest the
    # route ever gets to a road after leaving the start. If the finish is
    # farther, the descent ran past a usable pickup and the rider hikes back.
    d_road = terrain.road_distance_m[rows, cols]
    k = max(1, len(d_road) // 4)   # ignore the start's own road proximity
    best_after = float(d_road[k:].min()) if len(d_road) > k else float(d_road[-1])
    overshoot = max(0.0, float(d_road[-1]) - best_after)
    return Route(
        rows=rows,
        cols=cols,
        length_m=float(seg_len.sum()),
        total_climb_m=float(np.nansum(climbs)),
        grade_std_pct=float(np.nanstd(seg_grade)) if len(seg_grade) else 0.0,
        crosses_hazard=bool(terrain.hazard[rows, cols].any()),
        road_crossings=crossings,
        crosses_cliff=bool(terrain.cliff[rows, cols].any()),
        pickup_overshoot_m=overshoot,
        road_along_m=along_m,
    )


def build_routes(
    pairs: list[CandidatePair],
    data: Datasets,
    terrain: TerrainAnalysis,
    cfg: Config,
) -> list[CandidatePair]:
    """Attach 1-2 example routes to each pair; drop pairs with no viable
    route (unreachable, or only reachable by crossing a hazard).

    Per pair, the graph is built on the corridor's bounding box only —
    a few hundred cells on a side — so cost scales with pair count times a
    small constant, not with grid size."""
    cell = data.grid.cell_size_m
    kept: list[CandidatePair] = []
    n_stub = n_climby = n_crossy = n_cliff = n_overshoot = 0
    for p in pairs:
        corridor = _corridor_mask(data.grid.shape, p.start, p.end,
                                  p.run_m, cell, cfg)
        rr, cc = np.nonzero(corridor)
        r0, r1 = int(rr.min()), int(rr.max()) + 1
        c0, c1 = int(cc.min()), int(cc.max()) + 1
        win = np.s_[r0:r1, c0:c1]

        dev = np.abs(terrain.slope_pct[win] - p.avg_grade_pct) / 100.0
        cost = np.ascontiguousarray(1.0 + 4.0 * dev, dtype=np.float64)
        cost[terrain.unrideable[win]] = 50.0  # only as a last resort
        cost[terrain.stream[win]] = np.maximum(
            cost[terrain.stream[win]], cfg.params.stream_crossing_cost)
        # Cliffs: extreme cost, but passable so the router can find a
        # ride-around; if the final route still crosses one, no ride-around
        # existed and the pair is rejected below.
        cost[terrain.cliff[win]] = np.maximum(
            cost[terrain.cliff[win]], cfg.params.route_cliff_cost)
        # Road-crossing penalties: a trail can share tread with dirt (2) and
        # jeep (1) roads for free, but must avoid gravel/paved/highway and
        # especially residential grids. Additive per-cell cost => the route
        # crosses such a road perpendicular (few cells) and refuses to run
        # through a subdivision (many cells).
        rc = data.road_class[win]
        cost[rc == 3] += cfg.params.route_cross_gravel_cost
        cost[(rc == 4) | (rc == 5)] += cfg.params.route_cross_paved_cost
        cost[terrain.hazard[win]] = IMPASSABLE
        cost[np.isnan(data.dem_m[win])] = IMPASSABLE
        cost[~corridor[win]] = IMPASSABLE

        start_local = (p.start.row - r0, p.start.col - c0)
        end_local = (p.end.row - r0, p.end.col - c0)
        graph = GridGraph(cost, cell)
        sp = graph.shortest_path(start_local, end_local)
        if sp is None:
            continue
        first = _route_stats(sp[0] + r0, sp[1] + c0, data, terrain)
        if first.crosses_hazard:
            continue
        if first.crosses_cliff:
            n_cliff += 1  # cliff with no ride-around inside the corridor
            continue
        if (units.meters_to_feet(first.pickup_overshoot_m)
                > cfg.hard.max_pickup_overshoot_ft):
            n_overshoot += 1  # ran past its own pickup road
            continue
        # Anti-stub gate: the descent must dwarf the road-access walks.
        access_walk = p.start.road_dist_m + p.end.road_dist_m
        if first.length_m < cfg.hard.min_route_to_access_ratio * access_walk:
            n_stub += 1
            continue
        if first.total_climb_ft > cfg.hard.max_route_climb_ft:
            n_climby += 1
            continue
        if (first.road_crossings > cfg.hard.max_route_road_crossings
                or units.meters_to_feet(first.road_along_m)
                > cfg.hard.max_road_along_ft):
            n_crossy += 1  # threads streets, or rides the road itself
            continue
        p.routes = [first]

        if cfg.params.routes_per_pair >= 2:
            band = np.zeros(cost.shape, dtype=bool)
            band[sp[0], sp[1]] = True
            band = buffer_mask(band, cfg.params.route_alternate_corridor_m,
                               cell)
            alt_cost = cost.copy()
            inflate = band & (alt_cost < IMPASSABLE)
            alt_cost[inflate] *= cfg.params.route_alternate_penalty
            sp2 = GridGraph(alt_cost, cell).shortest_path(start_local,
                                                          end_local)
            if sp2 is not None and not np.array_equal(sp2[0], sp[0]):
                second = _route_stats(sp2[0] + r0, sp2[1] + c0, data, terrain)
                if not second.crosses_hazard:
                    p.routes.append(second)
        kept.append(p)
    log.info("Route generation: %d/%d pairs viable (%d stubs, %d over climb "
             "cap, %d over road-crossing cap, %d cliff-blocked, %d overshot "
             "pickup)",
             len(kept), len(pairs), n_stub, n_climby, n_crossy, n_cliff,
             n_overshoot)
    return kept
